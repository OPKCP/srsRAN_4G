#!/usr/bin/env bash
# =============================================================================
# start-all.sh — запуск компонентов СТЕНДА на base5 (узел БС1).
#
# На этом узле расположены БС1 (1815 МГц) и её дашборд.
# Ядро сети и остальные сервисы поднимаются с pi5-2 (~/start-all.sh).
# Порядок: сначала БС, затем дашборд (чтобы дашборд сразу видел лог).
# =============================================================================
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"

echo "########## 1/2. БС1 (base5, 1815 МГц) ##########"
bash "$HERE/start-bs.sh"; RC_BS=$?

echo
echo "########## 2/2. Дашборд БС1 ##########"
bash "$HERE/start-web.sh"; RC_WEB=$?

echo
echo "=================== СВОДКА ==================="
printf "  БС1 (base5)       : rc=%s\n" "$RC_BS"
printf "  дашборд БС1       : rc=%s\n" "$RC_WEB"
echo "=============================================="
if [ "$RC_BS" -ne 0 ] || [ "$RC_WEB" -ne 0 ]; then
  echo "[ВНИМАНИЕ] не все компоненты base5 запустились."; exit 1
fi
echo "[OK] Компоненты base5 запущены."
