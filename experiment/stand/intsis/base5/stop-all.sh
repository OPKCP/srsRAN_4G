#!/usr/bin/env bash
# =============================================================================
# stop-all.sh — остановка компонентов стенда на base5 (узел БС1).
# Порядок обратный: дашборд, затем БС.
# =============================================================================
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"

echo "########## 1/2. Дашборд БС1 ##########"
bash "$HERE/stop-web.sh"; RC_WEB=$?

echo
echo "########## 2/2. БС1 (base5) ##########"
bash "$HERE/stop-bs.sh"; RC_BS=$?

echo
echo "=================== СВОДКА ==================="
printf "  дашборд БС1       : rc=%s\n" "$RC_WEB"
printf "  БС1 (base5)       : rc=%s\n" "$RC_BS"
echo "=============================================="
echo "[OK] Компоненты base5 остановлены."
