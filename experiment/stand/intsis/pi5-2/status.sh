#!/usr/bin/env bash
# =============================================================================
# status.sh — ПОКАЗАТЬ СОСТОЯНИЕ СТЕНДА (только чтение, ничего не меняет).
#
# Запуск (на pi5-2, из домашнего каталога):
#     ./status.sh
#
# Скрипт печатает понятную сводку: какие компоненты работают, какие стоят,
# подключены ли базовые станции к ядру, доступны ли веб-сервисы.
# Можно запускать в любой момент — безопасно.
# =============================================================================
set -uo pipefail

# Основной IP узла: на wlan0 два адреса (192.168.1.26 — основной,
# 192.168.1.20 — вторичный для БС2), поэтому исключаем .20.
IP="$(ip -4 addr show wlan0 2>/dev/null | grep -oE 'inet [0-9.]+' | awk '{print $2}' | grep -v '^192\.168\.1\.20$' | head -1)"
[ -z "$IP" ] && IP="$(hostname -I | awk '{print $1}')"

# --- Вспомогательные функции -------------------------------------------------
# Строка состояния контейнера: печатаем РАБОТАЕТ / ПАУЗА / ОСТАНОВЛЕН / НЕТ
line() {  # line <человеческое имя> <имя контейнера>
  local title="$1" c="$2" st
  st="$(docker inspect -f '{{.State.Status}}' "$c" 2>/dev/null)" || st="absent"
  case "$st" in
    running)
      if [ "$(docker inspect -f '{{.State.Paused}}' "$c" 2>/dev/null)" = "true" ]; then
        echo "  [ПАУЗА]      ${title}  (контейнер ${c} приостановлен)"
      else
        echo "  [РАБОТАЕТ]   ${title}  (контейнер ${c})"
      fi ;;
    paused)  echo "  [ПАУЗА]      ${title}  (контейнер ${c} приостановлен)" ;;
    exited)  echo "  [ОСТАНОВЛЕН] ${title}  (контейнер ${c})" ;;
    absent)  echo "  [НЕТ]        ${title}  (контейнера ${c} нет)" ;;
    *)       echo "  [${st}] ${title}  (контейнер ${c})" ;;
  esac
}

# Проверка веб-адреса: печатаем код ответа (200 = всё хорошо)
webcheck() {  # webcheck <подпись> <url>
  local title="$1" url="$2" code
  code="$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 "$url" 2>/dev/null)"
  [ -z "$code" ] && code="нет ответа"
  echo "  ${title}  ->  ${url}   код ${code}"
}

echo "################################################################"
echo "#  СОСТОЯНИЕ СТЕНДА srsRAN 4G"
echo "#  Узел: $(hostname) (${IP})"
echo "#  Время: $(date '+%d.%m.%Y %H:%M')"
echo "################################################################"
echo

# =============================================================================
# 1. ЯДРО СЕТИ (Open5GS + MongoDB) — только на pi5-2
# =============================================================================
echo "=== 1. ЯДРО СЕТИ (Open5GS), узел pi5-2 ==="
line "Open5GS (MME/SGW/PGW/HSS)" open5gs
line "MongoDB (база абонентов)"  open5gs-mongodb

if [ "$(docker inspect -f '{{.State.Running}}' open5gs 2>/dev/null)" = "true" ]; then
  echo "  --- слушает (нужно для базовых станций) ---"
  if docker exec open5gs sh -c 'ss -l -A sctp -n 2>/dev/null | grep -q 36412'; then
    echo "  [OK] S1-MME  (SCTP 36412) — сюда подключаются БС"
  else
    echo "  [ВНИМАНИЕ] S1-MME (SCTP 36412) НЕ слушает"
  fi
  if docker exec open5gs sh -c 'ss -lun 2>/dev/null | grep -q ":2152"'; then
    echo "  [OK] GTP-U   (UDP 2152)   — передача данных абонентов"
  else
    echo "  [ВНИМАНИЕ] GTP-U (UDP 2152) НЕ слушает"
  fi
  sgi="$(docker exec open5gs sh -c 'ip -4 addr show ogstun 2>/dev/null | grep inet' 2>/dev/null | awk '{print $2}')"
  if [ -n "$sgi" ]; then
    echo "  [OK] SGi-шлюз абонентов (ogstun): $sgi"
  else
    echo "  [ВНИМАНИЕ] интерфейс ogstun без адреса — у абонентов не будет интернета"
  fi
  echo "  --- подключённые базовые станции (сейчас) ---"
  # Показываем УСТАНОВЛЕННЫЕ SCTP-соединения на порту S1AP (36412) — это и есть
  # реально подключённые сейчас базовые станции.
  conns="$(docker exec open5gs sh -c 'ss -A sctp -n 2>/dev/null | grep -E "36412" | grep -v LISTEN' 2>/dev/null \
           | grep -oE '192\.168\.1\.[0-9]+' | grep -v '^192\.168\.1\.26$' | sort -u | tr '\n' ' ')"
  if [ -n "$conns" ]; then
    echo "  [OK] подключены адреса БС: ${conns}"
    echo "      (192.168.1.25 — БС1; 192.168.1.20 — БС2, если она работает)"
  else
    echo "  [ВНИМАНИЕ] ни одна БС сейчас не подключена к ядру"
  fi
fi
echo

# =============================================================================
# 2. БАЗОВЫЕ СТАНЦИИ
# =============================================================================
echo "=== 2. БАЗОВЫЕ СТАНЦИИ ==="
line "БС2 / eNB2 (1811 МГц, pi5-2)" enb2
# Наличие SDR-платы на этом узле (ищем по USB-идентификаторам Ettus/NI)
if lsusb 2>/dev/null | grep -qiE '2500:|2505:|3923:'; then
  echo "  [OK] SDR-плата на этом узле обнаружена: $(lsusb | grep -iE '2500:|2505:|3923:' | sed 's/^Bus [0-9]* Device [0-9]*: ID //')"
else
  echo "  [ВНИМАНИЕ] на pi5-2 SDR-плата НЕ обнаружена — БС2 запустить нельзя"
fi
echo "  --- БС1 (base5, 1815 МГц) — проверяем по сети ---"
ssh -o BatchMode=yes -o ConnectTimeout=8 base5 \
  'echo "  Модель: $(lsusb | grep -iE "2500:|2505:" | head -1 | sed "s/.*ID //" || echo "плата не найдена")"; docker ps --format "{{.Names}} {{.Status}}" | grep -E "^enb " | sed "s/^/  Контейнер: /" || echo "  [ОСТАНОВЛЕН] контейнер enb"' 2>/dev/null \
  || echo "  [ОШИБКА] нет связи с base5 (проверьте сеть/ssh)"
echo

# =============================================================================
# 3. ВЕБ-СЕРВЕРЫ И МОНИТОРИНГ
# =============================================================================
echo "=== 3. ВЕБ-СЕРВЕРЫ И МОНИТОРИНГ (pi5-2) ==="
line "webserve (файлы абонентам)" webserve
line "дашборд ядра"              srsran-dashboard-epc
line "дашборд БС2"               srsran-dashboard-enb2
line "Prometheus (метрики)"      prometheus
line "Grafana (графики)"         grafana
echo "  --- доступность в браузере ---"
webcheck "дашборд БС2"  "http://$IP:5000/"
webcheck "дашборд ядра" "http://$IP:5001/"
webcheck "Prometheus"   "http://$IP:9091/"
webcheck "Grafana"      "http://$IP:3000/"
echo "  (код 200 — открывается; 302 — перенаправление, тоже нормально)"
echo "  --- веб-сервер для телефонов (внутри сети оператора) ---"
code="$(docker exec open5gs curl -s -o /dev/null -w '%{http_code}' --max-time 5 http://10.0.0.1:8080/ 2>/dev/null)"
echo "  http://10.0.0.1:8080/  (открывать с телефона)  код ${code:-нет ответа}"
echo

# =============================================================================
# 4. ИТОГ
# =============================================================================
echo "################################################################"
echo "#  ЧТО ДАЛЬШЕ                                                  #"
echo "#    ./start-all.sh  — запустить весь стенд                    #"
echo "#    ./stop-all.sh   — остановить весь стенд                   #"
echo "#    ./status.sh     — снова показать это состояние            #"
echo "################################################################"
