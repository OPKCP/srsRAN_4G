#!/usr/bin/env bash
# ==============================================================================
# run_python_enb_rpi.sh
# Синтетический тест: python-контейнер на малинке (RPi5), имитирующий eNB (БС).
# Будет устанавливать связь с ядром на компьютере (192.168.1.10) на целевые порты.
# Детерминированный запуск: docker rm -f старого + запуск нового контейнера `enb`.
#
# Согласно методике — проверка связи выполняется ИЗНУТРИ контейнера
# (клиент-сервер к нужным IP/портам ядра).
# ==============================================================================
set -euo pipefail

NAME="enb"
IMG="python:3.12-slim"
EPC_IP="${EPC_IP:-192.168.1.10}"   # IP компьютера (хост Windows) — куда ходит БС
S1AP_PORT=36412
GTP_PORT=2152

# --- Удаление старого контейнера ---
docker rm -f "$NAME" >/dev/null 2>&1 || true
echo "[OK] Удалён старый контейнер $NAME (если был)"

# --- Запуск нового контейнера ---
docker run -d --name "$NAME" --hostname "$NAME" \
  --network host \
  "$IMG" sleep infinity

echo "[OK] Контейнер $NAME запущен (python, network=host, sleep infinity)"

echo "=== Контейнер $NAME (python/eNB-test) готов ==="
echo "Целевой EPC: $EPC_IP (порты S1AP=$S1AP_PORT sctp, GTP=$GTP_PORT udp)"
